import {test,expect} from '@playwright/test'

for(const width of [390,1440])test(`coded visual journey at ${width}px preserves editorial and collection behavior`,async({page})=>{
 await page.setViewportSize({width,height:width===390?844:900})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/api/editorial',async route=>{await new Promise(resolve=>setTimeout(resolve,200));await route.fulfill({status:503,body:'Unavailable'})})
 await page.goto('/?prototype=discover')
 await expect(page.locator('.reference-discover')).toBeVisible()
 await expect(page.locator('.reference-photo img')).toHaveCount(5)
 await page.getByLabel('Your discovery prompt').fill('Quiet interiors and sculptural seating')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-generate')).toBeVisible()
 await expect(page.locator('.visual-pending')).toContainText('Composing your magazine')
 await expect(page.locator('.visual-reader')).toBeVisible()
 await expect(page.getByText('AI not used').first()).toBeVisible()
 const hotspot=page.locator('.visual-reader .image-hotspot').first()
 await expect(hotspot).toBeVisible()
 await hotspot.focus()
 await page.keyboard.press('Enter')
 await expect(page.locator('.visual-reader .editorial-reveal')).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(page.locator('.visual-reader .editorial-reveal')).toBeHidden()
 await page.locator('.visual-reader-related').click()
 await expect(page.locator('.visual-journey')).toBeVisible()
 await page.locator('.journey-collect').click()
 await page.locator('.dialog-close').click()
 await page.getByRole('button',{name:'Your collection'}).click()
 await expect(page.locator('.visual-collect')).toBeVisible()
 await page.getByRole('button',{name:'Revisit'}).click()
 await expect(page.locator('.visual-journey')).toBeVisible()
 await page.locator('.dialog-close').click()
 await page.getByRole('button',{name:'Your collection'}).click()
 await page.reload()
 await page.getByRole('button',{name:'Your collection'}).click()
 await expect(page.getByRole('button',{name:'Remove',exact:true}).first()).toBeVisible()
 await page.getByRole('button',{name:'Remove',exact:true}).first().click()
 await expect(page.getByText('Your collection is waiting for a first discovery.')).toBeVisible()
})
