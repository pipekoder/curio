import {test,expect} from '@playwright/test'

for(const width of [390,768,1440])test(`coded visual journey at ${width}px preserves editorial and collection behavior`,async({page})=>{
 await page.setViewportSize({width,height:width===390?844:900})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/api/editorial',async route=>{await new Promise(resolve=>setTimeout(resolve,2200));await route.fulfill({status:503,body:'Unavailable'})})
 await page.goto('/?prototype=discover')
 await expect(page.locator('.reference-discover')).toBeVisible()
 await expect(page.locator('.reference-photo img')).toHaveCount(5)
 const mediaReady=async(selector:string,count:number)=>{const stage=page.locator(selector);const before=await stage.boundingBox();const photos=stage.locator('img[src^="/editorial/"]');await expect(photos).toHaveCount(count);for(const photo of await photos.all())await expect.poll(()=>photo.evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0&&img.naturalHeight>0)).toBe(true);const after=await stage.boundingBox();expect(Math.abs((before?.width??0)-(after?.width??0))).toBeLessThan(1);expect(Math.abs((before?.height??0)-(after?.height??0))).toBeLessThan(1)}
 await mediaReady('.reference-discover',5)
 await page.getByLabel('Your discovery prompt').fill('Quiet interiors and sculptural seating')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-generate')).toBeVisible()
 await expect(page.locator('.visual-pending')).toContainText('Composing your magazine')
 await mediaReady('.visual-generate',5)
 await expect(page.locator('.visual-reader')).toBeVisible()
 await mediaReady('.visual-reader',5)
 await expect(page.getByText('AI not used').first()).toBeVisible()
 const hotspot=page.locator('.visual-reader .chair-demo-hotspot')
 await expect(hotspot).toBeVisible()
 await expect(page.locator('.visual-reader-intro h2')).toHaveText('The Lounge Chair')
 await expect(page.locator('.visual-reader-image')).toHaveCount(0)
 await expect(page.locator('.visual-reader-back-photo img')).toHaveAttribute('src','/editorial/read/16_read_chair.png')
 await hotspot.focus()
 await page.keyboard.press('Enter')
 await expect(page.locator('.chair-demo-detail')).toBeVisible()
 await expect(page.locator('.chair-demo-detail')).toContainText('fictional, not for sale')
 await expect(page.locator('.chair-demo-detail')).toContainText('material')
 await page.getByRole('button',{name:'Explore related story'}).click()
 await expect(page.locator('.visual-journey')).toBeVisible()
 await expect(page.locator('.visual-journey')).toContainText('Arc Lounge Chair')
 await mediaReady('.visual-journey',7)
 await page.locator('.journey-collect').click()
 await page.locator('.dialog-close').click()
 await page.getByRole('button',{name:'Your collection'}).click()
 await expect(page.locator('.visual-collect')).toBeVisible()
 await mediaReady('.visual-collect',6)
 await page.getByRole('button',{name:'Revisit'}).click()
 await expect(page.locator('.visual-journey')).toBeVisible()
 await mediaReady('.visual-journey',7)
 await page.locator('.dialog-close').click()
 await page.getByRole('button',{name:'Your collection'}).click()
 await page.reload()
 await page.getByRole('button',{name:'Your collection'}).click()
 await expect(page.getByRole('button',{name:'Remove',exact:true}).first()).toBeVisible()
 await page.getByRole('button',{name:'Remove',exact:true}).first().click()
 await expect(page.getByText('Your collection is waiting for a first discovery.')).toBeVisible()
})
