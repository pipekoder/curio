test('validated Muse-shaped plans control the primary image, headline and edition pages',async({page})=>{
 await page.route('**/api/editorial',async route=>{
  const prompt=String(route.request().postDataJSON()?.prompt??'')
  const travel=prompt.toLowerCase().includes('woodland')
  const plan=travel?plans.travel:liveHome.plan
  await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({source:'meta',retrieval:'fictional',cached:false,plan,items:plan.features.map(f=>({id:f.catalogId,image:{id:f.assetId}}))})})
 })
 await page.goto('/')
 await page.getByLabel('Your discovery prompt').fill('paper quiet lamp')
 await page.getByRole('checkbox',{name:/Use Meta AI/}).check()
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-reader')).toHaveAttribute('data-asset-id','asset-home-lamp-v1')
 await expect(page.locator('.visual-reader-intro h2')).toHaveText(liveHome.plan.features[0].headline)
 await expect(page.locator('.visual-reader-back-photo img')).toHaveAttribute('src','/catalog/home-lamp.svg')
 await expect(page.locator('.visual-reader-back-photo .image-hotspot').first()).toBeVisible()
 await expect(page.getByText('Validated Meta editorial plan')).toBeVisible()
 await page.getByRole('button',{name:/Read edition page 2:/}).click()
 await expect(page.locator('.visual-reader')).toHaveAttribute('data-asset-id','asset-home-chair-v1')
 await expect(page.locator('.visual-reader-intro h2')).toHaveText(liveHome.plan.features[1].headline)
 await page.getByRole('button',{name:'Refine with a new prompt'}).click()
 await page.getByLabel('Your discovery prompt').fill('Surprise me with woodland path walking travel')
 await page.getByRole('checkbox',{name:/Use Meta AI/}).check()
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-reader')).toHaveAttribute('data-asset-id','asset-travel-walk-v1')
 await expect(page.locator('.visual-reader-intro h2')).toHaveText(plans.travel.features[0].headline)
 await expect(page.locator('.visual-reader-back-photo img')).toHaveAttribute('src','/catalog/travel-walk.svg')
 await expect(page.getByText('Validated Meta editorial plan')).toBeVisible()
})

