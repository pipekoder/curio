import {test,expect} from '@playwright/test'

test('a direct /explore visit has a same-origin, refresh-safe empty state',async({page})=>{
 await page.goto('/explore')
 await expect(page.getByRole('heading',{name:'Your next discovery begins with a prompt.'})).toBeVisible()
 await expect(page.getByRole('link',{name:'Skip to reader'})).toHaveAttribute('href','#reader-heading')
 await page.reload()
 await expect(page.getByRole('button',{name:/Shape your curiosity/})).toBeVisible()
 await page.getByRole('button',{name:/Shape your curiosity/}).click()
 await expect(page).toHaveURL('http://127.0.0.1:4173/')
 await expect(page.locator('.reference-discover')).toBeVisible()
})

test('generation opens /explore, preserves the validated edition through reload and browser history',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/api/editorial',route=>route.fulfill({status:503,body:'AI disabled'}))
 await page.goto('/')
 await page.getByLabel('Your discovery prompt').fill('A rounded lounge chair in a quiet room')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page).toHaveURL('http://127.0.0.1:4173/explore')
 await expect(page.locator('.visual-reader')).toBeVisible()
 expect(await page.evaluate(()=>sessionStorage.getItem('curio.explore.edition.v1'))).not.toContain('A rounded lounge chair in a quiet room')
 await page.getByRole('button',{name:/Read edition page 2/}).click()
 await expect(page).toHaveURL(/\/explore\?page=2$/)
 const asset=await page.locator('.visual-reader').getAttribute('data-asset-id')
 const title=await page.locator('#reader-heading').textContent()
 await expect(page.locator('.reader-sequence .reader-chapter')).toHaveCount(2)
 await expect(page.getByText('AI not used').first()).toBeVisible()
 await page.reload()
 await expect(page.locator('.visual-reader')).toHaveAttribute('data-asset-id',asset!)
 await expect(page.locator('#reader-heading')).toHaveText(title!)
 await page.getByRole('link',{name:'Continue the issue'}).click()
 await expect(page.locator('#reader-sequence')).toBeInViewport()
 await page.getByRole('button',{name:'Explore the story'}).first().click()
 await expect(page.locator('.visual-journey')).toBeVisible()
 await page.getByRole('button',{name:'Return to reading'}).click()
 await page.getByRole('button',{name:'Refine with a new prompt'}).click()
 await expect(page).toHaveURL('http://127.0.0.1:4173/')
 await page.goBack()
 await expect(page).toHaveURL(/\/explore\?page=2(?:#reader-sequence)?$/)
 await expect(page.locator('.visual-reader')).toBeVisible()
 await page.goForward()
 await expect(page.locator('.reference-discover')).toBeVisible()
})

test('an invalid saved edition cannot be rendered on /explore',async({page})=>{
 await page.goto('/')
 await page.evaluate(()=>sessionStorage.setItem('curio.explore.edition.v1',JSON.stringify({version:1,savedAt:Date.now(),source:'meta',retrieval:'d1',plan:{title:'Unapproved',features:[]},prefs:{}})))
 await page.goto('/explore')
 await expect(page.getByRole('heading',{name:'Your next discovery begins with a prompt.'})).toBeVisible()
 await expect(page.locator('.visual-reader')).toHaveCount(0)
})

test('reload rechecks asset identity and withholds a changed or unpublished version',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/api/editorial',route=>route.fulfill({status:503,body:'AI disabled'}))
 await page.goto('/')
 await page.getByLabel('Your discovery prompt').fill('Rounded lounge chair in a quiet room')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-reader')).toBeVisible()
 await page.evaluate(()=>{const key='curio.explore.edition.v1';const saved=JSON.parse(sessionStorage.getItem(key)!) as {plan:{features:{assetId:string}[]}};saved.plan.features[0].assetId=`version-${'0'.repeat(64)}`;sessionStorage.setItem(key,JSON.stringify(saved))})
 await page.reload()
 await expect(page.getByRole('heading',{name:'Your next discovery begins with a prompt.'})).toBeVisible()
 await expect(page.locator('.visual-reader')).toHaveCount(0)
})

test('mobile Reader scroll rhythm remains usable with reduced motion and touch',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'reduce'})
 const page=await context.newPage()
 try{
 await page.route('**/api/editorial',route=>route.fulfill({status:503,body:'AI disabled'}))
 await page.goto('/')
 await page.getByLabel('Your discovery prompt').fill('Rounded lounge chair in a quiet room')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-reader')).toBeVisible()
 await expect(page.locator('.reader-chapter')).toHaveCount(2)
 expect(await page.locator('.reader-chapter-image').first().evaluate(el=>getComputedStyle(el).animationName)).toBe('none')
 await page.getByRole('button',{name:'Explore image details'}).tap()
 await expect(page.locator('.chair-demo-hotspot')).toBeVisible()
 await page.locator('.chair-demo-hotspot').tap()
 await expect(page.locator('.chair-demo-detail')).toBeVisible()
 await expect.poll(async()=>{const box=await page.locator('.chair-demo-detail').boundingBox();return box?.y??9999}).toBeLessThan(700)
 await expect.poll(async()=>{const box=await page.locator('.visual-reader-back-photo').boundingBox();return (box?.y??-999)+(box?.height??0)}).toBeGreaterThan(350)
 await page.getByRole('button',{name:'Collect this image'}).tap()
 await expect(page.getByRole('status').filter({hasText:'Saved to your collection'})).toBeVisible()
 }finally{await context.close()}
})
