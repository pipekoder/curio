import {test,expect} from '@playwright/test'
for (const width of [1440,390]) test(`editorial hotspots are quiet, accessible and continuous at ${width}px`, async({browser})=>{
 const context=await browser.newContext({viewport:{width,height:1000},hasTouch:width===390,reducedMotion:'reduce'})
 const page=await context.newPage()
 try {
  await page.route('**/api/editorial',route=>route.fulfill({status:503,json:{status:'disabled'}}))
  await page.goto('http://127.0.0.1:4173/?legacy=1')
  await page.getByRole('textbox').fill('Create a quiet Scandinavian magazine about home lighting and reading rooms.')
  await page.getByRole('button',{name:/Generate.*magazine/i}).click()
  const feature=page.locator('.personal-feature').first()
  const hotspot=feature.getByRole('button',{name:'Explore Paper shade'})
  await hotspot.scrollIntoViewIfNeeded()
  await page.mouse.move(0,0)
  await expect(feature.locator('.region-dimming')).toHaveCount(0)
  await expect(hotspot).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
  if(width===390) await hotspot.tap()
  else {await hotspot.focus();await page.keyboard.press('Enter')}
  await expect(feature.getByRole('region',{name:'Paper shade editorial reveal'})).toBeVisible()
  expect(await hotspot.evaluate(e=>e.getBoundingClientRect().width)).toBeGreaterThanOrEqual(44)
  await expect(feature.locator('.editorial-reveal')).toHaveCSS('animation-name','none')
  await feature.screenshot({path:`test-results/ux-v2-${width}.png`})
  await feature.getByRole('button',{name:/Read the connected story/}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText(/light.and.shadow|curve.and.space/)
  await page.getByRole('dialog').getByRole('button',{name:/Collect story/i}).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:/Your collection \(/}).click()
  await expect(page.getByRole('dialog')).toContainText(/Pebble Chair|Paper Moon Lamp/)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 } finally {await context.close()}
})
test('grounded editorial V2 copy provides a question leading into the existing story journey',async({page})=>{
 const {readFileSync}=await import('node:fs')
 const plan=JSON.parse(readFileSync('tests/fixtures/editorial-v2-grounded.json','utf8'))
 const {curationCatalog}=await import('../shared/catalog')
 await page.route('**/api/editorial',route=>route.fulfill({json:{plan,items:curationCatalog,source:'meta',retrieval:'fictional',cached:false}}))
 await page.goto('/?legacy=1')
 await page.getByRole('textbox').fill('Scandinavian home light and space')
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.getByRole('heading',{name:plan.title})).toBeVisible()
 await page.getByRole('button',{name:`${plan.features[0].discoveryQuestion} →`}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.getByRole('dialog').getByRole('button',{name:'Collect story'})).toBeVisible()
})
