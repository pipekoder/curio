import {test,expect} from '@playwright/test'

test('sentence slots, custom words, surprise and manual entry share the existing Discover submission',async({page})=>{
 await page.setViewportSize({width:1440,height:900})
 await page.route('**/api/editorial',route=>route.fulfill({status:503,body:'AI disabled'}))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Shape Your Curiosity'})).toBeVisible()
 await expect(page.locator('.reference-photo img')).toHaveCount(5)
 await page.getByRole('button',{name:'Places & culture'}).click()
 await expect(page.getByLabel('Your discovery prompt')).toHaveValue(/quiet coastal homes in Northern Europe/)
 await page.getByRole('button',{name:/Change place: Northern Europe/}).click()
 await page.getByLabel('Your own words').fill('coastal Japan')
 await page.getByRole('button',{name:'Apply'}).click()
 await expect(page.getByLabel('Your discovery prompt')).toHaveValue(/in coastal Japan/)
 await page.getByRole('button',{name:/Surprise me/}).click()
 await expect(page.getByLabel('Your discovery prompt')).toHaveValue(/unexpected links to fashion/)
 await page.getByLabel('Your discovery prompt').fill('A completely custom magazine about calm reading rooms')
 await expect(page.getByLabel('Your discovery prompt')).toHaveValue('A completely custom magazine about calm reading rooms')
 await page.getByRole('button',{name:'Generate magazine'}).click()
 await expect(page.locator('.visual-reader')).toBeVisible()
 await expect(page.getByText('AI not used').first()).toBeVisible()
})

test('mobile keyboard and reduced-motion interaction keeps the orbital composition and consent accessible',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await expect(page.locator('.reference-photo img')).toHaveCount(5)
 await expect(page.locator('.reference-orbits')).toBeVisible()
 await page.getByRole('button',{name:/Change subject: emerging brands/}).focus()
 await page.keyboard.press('Enter')
 await expect(page.getByRole('group',{name:'Choose subject'})).toBeVisible()
 await page.getByRole('button',{name:'independent ceramic studios'}).click()
 await expect(page.getByLabel('Your discovery prompt')).toHaveValue(/independent ceramic studios/)
 await expect(page.getByRole('checkbox',{name:/Use Meta AI/})).not.toBeChecked()
 expect(await page.locator('.prompt-library').evaluate(element=>getComputedStyle(element).animationName)).toBe('none')
})
