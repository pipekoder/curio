import { expect, test } from "@playwright/test";
for (const width of [1440, 390]) test(`one prompt generates and refines a magazine at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  const requests: { prompt: string; consent: boolean }[] = [];
  await page.route("**/api/editorial", route => { requests.push(route.request().postDataJSON()); return route.fulfill({ status: 503, json: { error: "AI off" } }); });
  await page.goto("/");
  const prompt = page.getByRole("textbox", { name: "Your discovery prompt" });
  await expect(prompt).toBeVisible();
  expect((await prompt.boundingBox())!.y).toBeLessThan(800);
  await expect(page.getByRole("spinbutton")).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Focused A closer|Balanced Connections|Surprise Me A little/ })).toHaveCount(0);
  await expect(page.locator(".prompt-suggestions [aria-pressed]")).toHaveCount(0);
  await page.getByRole("button", { name: "Try a prompt: Quiet rooms" }).click();
  await expect(prompt).toBeFocused();
  await expect(prompt).toHaveValue(/paper lamps/);
  expect(requests).toHaveLength(0);
  await page.locator(".prompt-composer").screenshot({ path: `test-results/prompt-composer-${width}.png` });
  await prompt.focus(); await page.keyboard.press("Control+Enter");
  await expect(page.getByRole("heading", { name: "The art of quiet rooms" })).toBeFocused();
  expect(requests).toHaveLength(1);
  expect(Object.keys(requests[0]).sort()).toEqual(["consent", "prompt"]);
  expect(requests[0].consent).toBe(false);
  await page.getByRole("button", { name: "Refine with a new prompt ↑" }).click();
  await expect(prompt).toBeFocused();
  await page.getByRole("checkbox").check();
  await prompt.fill("Surprise me with woodland paths, travel and unexpected horizons");
  await expect(page.getByRole("checkbox")).not.toBeChecked();
  await page.getByRole("button", { name: "Generate magazine" }).click();
  await expect(page.getByRole("heading", { name: "Into the open" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "The art of quiet rooms" })).toHaveCount(0);
  await expect(page.locator(".personal-edition")).toHaveCount(1);
  await expect(page.getByRole("log")).toHaveCount(0);
  expect(requests).toHaveLength(2);
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain("woodland");
});
test("asks one inline clarification only when every supported category is explicitly excluded", async ({ page }) => {
  let requests = 0;
  await page.route("**/api/editorial", route => { requests++; return route.abort(); });
  await page.goto("/");
  await page.getByLabel("Your discovery prompt").fill("No home, no fashion, no travel");
  await page.getByRole("button", { name: "Generate magazine" }).click();
  await expect(page.getByRole("alert")).toContainText("Include at least one");
  expect(requests).toBe(0);
});
